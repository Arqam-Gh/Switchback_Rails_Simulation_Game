// ----------------------------------------------------------------------------
// Check if a position is inside the grid.
// ----------------------------------------------------------------------------
// Returns true if x,y are within bounds.
// ----------------------------------------------------------------------------
bool isInBounds(int y, int x) {
    return(x<100 && x>=0 && y<100 && y>=0);
}

// ----------------------------------------------------------------------------
// Check if a tile is a track tile.
// ----------------------------------------------------------------------------
// Returns true if the tile can be traversed by trains.
// ----------------------------------------------------------------------------
bool isTrackTile(int y, int x) {
    return(grid[y][x]=='|' || grid[y][x]=='=' || grid[y][x]=='-' || grid[y][x]=='+' || grid[y][x]=='/' || grid[y][x]=='\\' || (grid[y][x]>='A'&&grid[y][x]<='Z'));
}

// ----------------------------------------------------------------------------
// Check if a tile is a switch.
// ----------------------------------------------------------------------------
// Returns true if the tile is 'A'..'Z'.
// ----------------------------------------------------------------------------
bool isSwitchTile(int y, int x) {
    return(grid[y][x]>='A'&&grid[y][x]<='Z');
}

// ----------------------------------------------------------------------------
// Get switch index from character.
// ----------------------------------------------------------------------------
// Maps 'A'..'Z' to 0..25, else -1.
// ----------------------------------------------------------------------------
int getSwitchIndex(char sw) {
    if(sw>='A'&&sw<='Z'){
    return(sw-'A');
}
else return -1;
}


// ----------------------------------------------------------------------------
// Check if a position is a spawn point.
// ----------------------------------------------------------------------------
// Returns true if x,y is a spawn.
// ----------------------------------------------------------------------------
bool isSpawnPoint(int y, int x) {
    return(grid[y][x]=='S');
}

// ----------------------------------------------------------------------------
// Check if a position is a destination.
// ----------------------------------------------------------------------------
// Returns true if x,y is a destination.
// ----------------------------------------------------------------------------
bool isDestinationPoint(int y, int x) {
    return(grid[y][x]=='D');
}

// ----------------------------------------------------------------------------
// Toggle a safety tile.
// ----------------------------------------------------------------------------
// Returns true if toggled successfully.
// ----------------------------------------------------------------------------
bool toggleSafetyTile(int y, int x) {
    if((x<100 && x>0 && y<100 && y>0)&&(grid[y][x]=='|' || grid[y][x]=='=' || grid[y][x]=='-' )){
        if(grid[y][x]=='=') {
            if(grid[y][x-1]==' ' && grid[y][x+1]==' ') {
            grid[y][x]='|';
            return 1;
            }
            if((grid[y][x-1]=='=' ||  grid[y][x-1]=='+' || grid[y][x-1]=='-') && (grid[y][x+1]=='=' ||  grid[y][x+1]=='+' || grid[y][x+1]=='-' )) {
            grid[y][x]='-';
            return 1;
            }
            return 0;
        }
        else if(grid[y][x]=='|' || grid[y][x]=='-') {
            grid[y][x]='=';
            return 1;
        }
        else return 0;
    }
    else return 0;
}
